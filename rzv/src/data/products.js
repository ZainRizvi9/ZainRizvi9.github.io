export function getFacetOptions(products, key) {
  return [...new Set(products.map((p) => p[key]))].sort();
}

export function getProduct(id) {
  return PRODUCTS.find((p) => p.id === id);
}

// Help content: size guide, keyed by which sizing scheme a product uses.
// Products sized "One Size" don't get a guide at all — showing one would be
// noise, not help.
export const SIZE_GUIDES = {
  letter: {
    label: "Chest / bust (in)",
    rows: [
      ["XS", "32–34"],
      ["S", "35–37"],
      ["M", "38–40"],
      ["L", "41–43"],
      ["XL", "44–46"],
    ],
  },
  waist: {
    label: "Waist (in)",
    rows: [
      ["28", "28–29"],
      ["30", "30–31"],
      ["32", "32–33"],
      ["34", "34–35"],
      ["36", "36–37"],
    ],
  },
};

export function getSizeGuide(sizes) {
  if (sizes.includes("XS")) return SIZE_GUIDES.letter;
  if (sizes.includes("28")) return SIZE_GUIDES.waist;
  return null;
}
